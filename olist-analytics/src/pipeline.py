# ------------------------------------------------------------------ synthetic plan files (SYNTHETIC)
# A finance-style plan the way it usually arrives: one wide sheet per year, title rows on top, the group name written
# only on the first line of its block (merged cells), a typo, 'n/a' and '-' in empty cells, a TOTAL row and two
# free-text columns. Power Query (Category Plan) cleans it; plan_mirror() repeats the same steps in SQL for the tests.
# The numbers are NOT Olist's: 2017 = 2017 actual x a fixed factor per group (the 2016 base is a few weeks of data),
# 2018 = 2017 actual (same month) x a growth assumption per group.
PLAN_FACTOR = {"Electronics & Appliances": 1.05, "Fashion & Accessories": 0.95, "Food, Drink & Pets": 1.10,
               "Health & Beauty": 0.90, "Home & Living": 1.00, "Leisure, Kids & Culture": 0.92,
               "Tools, Auto & Business": 1.08, "Uncategorised": 1.00}
PLAN_GROWTH = {"Electronics & Appliances": 1.45, "Fashion & Accessories": 1.40, "Food, Drink & Pets": 1.60,
               "Health & Beauty": 1.55, "Home & Living": 1.50, "Leisure, Kids & Culture": 1.35,
               "Tools, Auto & Business": 1.70, "Uncategorised": 1.00}
# how the group is typed in the sheet: 'Casa' is the Portuguese leftover the cleanup replaces, the others need Trim/Proper
PLAN_SPELLING = {"Home & Living": "Casa & Living", "Health & Beauty": "  health & beauty", "Tools, Auto & Business": "tools, auto & business "}
PROMO_SHARE = 0.1
OWNERS = ["R. Lima", "A. Souza", "M. Costa", "J. Alves"]


def write_plan(con):
    """data/plan/category_plan_{2017,2018}.csv; returns the number of 'n/a'/'-' cells written."""
    PLAN.mkdir(parents=True, exist_ok=True)
    rows = con.execute("""
        select p.category_group, year(i.order_date) y, month(i.order_date) m, sum(i.price)::double
        from mart.fact_order_items i join mart.dim_product p using (product_id)
        where i.is_valid and year(i.order_date) = 2017 group by all""").fetchall()
    actual = {(g, m): v for g, _, m, v in rows}
    blanks = 0
    for year in (2017, 2018):
        mult = PLAN_FACTOR if year == 2017 else PLAN_GROWTH
        months = [f"{year}-{m:02d}" for m in range(1, 13)]
        out = [[f"Olist category revenue plan {year} (SYNTHETIC, generated by src/pipeline.py)"] + [""] * 15,
               ["All figures in BRL, item price excluding freight. Prepared by FP&A."] + [""] * 15,
               ["Category Group", "Plan Line", *months, "Notes", "Owner"]]
        totals = [0.0] * 12
        for k, (group, f) in enumerate(mult.items()):
            plan = [round(actual.get((group, m), 0) * f, -2) for m in range(1, 13)]
            for line, share in (("Base", 1 - PROMO_SHARE), ("Promo", PROMO_SHARE)):
                cells = []
                for i, v in enumerate(plan):
                    if line == "Promo" and (group == "Uncategorised" or i % 5 == 4):
                        cells.append("n/a" if group == "Uncategorised" else "-")  # no promo budget that month
                        blanks += 1
                    else:
                        cells.append(f"{v * share:.0f}")
                        totals[i] += float(f"{v * share:.0f}")
                label = PLAN_SPELLING.get(group, group) if (line == "Base") else ""  # merged cell: first line only
                out.append([label, line, *cells, "check Black Friday" if line == "Base" and k == 0 else "",
                            OWNERS[k % len(OWNERS)]])
        out.append(["TOTAL", "", *[f"{t:.0f}" for t in totals], "", ""])
        with open(PLAN / f"category_plan_{year}.csv", "w", newline="", encoding="utf-8") as fh:
            csv.writer(fh).writerows(out)
    return blanks


def plan_mirror(con):
    """The Category Plan Power Query steps, repeated in SQL so the pipeline can test the result (and the HTML twin
    can show it). Same order: skip titles, headers, fill down, Casa->Home, trim/proper, drop TOTAL and notes,
    unpivot, split the month, non-numbers -> null."""
    con.execute("create schema if not exists mart")
    parts = []
    for year in (2017, 2018):
        path = (PLAN / f"category_plan_{year}.csv").as_posix()
        parts.append(f"""select *, {year} as file_year from read_csv('{path}', skip = 3, header = false, all_varchar = true,
            columns = {{'grp': 'varchar', 'line': 'varchar', {', '.join(f"'m{m:02d}': 'varchar'" for m in range(1, 13))},
                       'notes': 'varchar', 'owner': 'varchar'}})""")
    con.execute(f"""
        create or replace table mart.category_plan as
        with raw as ({' union all '.join(parts)}),
        numbered as (select *, row_number() over () as rn from raw),
        filled as (select *, last_value(grp ignore nulls) over (partition by file_year order by rn) as grp_filled from numbered),
        cleaned as (
            select file_year, line,
                   -- Text.Trim + Text.Proper (+ the Casa typo)
                   list_reduce(list_transform(string_split(trim(replace(grp_filled, 'Casa', 'Home')), ' '),
                       x -> upper(x[1]) || lower(x[2:])), (a, b) -> a || ' ' || b) as category_group,
                   m01, m02, m03, m04, m05, m06, m07, m08, m09, m10, m11, m12
            from filled where grp_filled <> 'TOTAL'),
        long as (unpivot cleaned on m01, m02, m03, m04, m05, m06, m07, m08, m09, m10, m11, m12
                 into name month value plan_text)
        select category_group, line as plan_line, file_year as year, substr(month, 2)::int as month_no,
               make_date(file_year, substr(month, 2)::int, 1) as month_start,
               try_cast(plan_text as double) as plan_revenue,
               substr(month, 2)::int = 11 as is_peak_month,
               (file_year * 10 + (substr(month, 2)::int + 2) // 3) as year_quarter
        from long""")


def plan_tests(con):
    """Rows that break the plan's contract; 0 = pass."""
    return [
        ("plan groups all exist in dim_product (left anti join = 0 rows)",
         "select count(*) from (select distinct category_group from mart.category_plan) p "
         "anti join (select distinct category_group from mart.dim_product) d using (category_group)"),
        ("plan has 8 groups x 2 lines x 24 months",
         "select abs(count(*) - 8 * 2 * 24) from mart.category_plan"),
        ("quarterly Group By reconciles with the monthly plan (to the real)",
         "select (abs((select sum(q) from (select sum(plan_revenue) q from mart.category_plan group by category_group, year_quarter))"
         " - (select sum(plan_revenue) from mart.category_plan)) > 0.5)::int"),
        ("plan TOTAL row equals the sum of the lines (no line lost in cleaning)",
         None),
    ]


def run_sql(con, path):
    t = time.perf_counter()
    con.execute(path.read_text().replace("{raw}", RAW.as_posix()))
    print(f"  ✓ {path.name:<20} {time.perf_counter() - t:5.1f}s")


def run_tests(con):
    text = (SQL / "90_tests.sql").read_text()
    tests = re.findall(r"-- name: (.+)\n(.+?;)", text)
    failed = 0
    for name, query in tests:
        bad = con.execute(query).fetchone()[0]
        failed += bad > 0
        print(f"  {'✓' if bad == 0 else '✗'} {name}{'' if bad == 0 else f'  ({bad} rows)'}")
    return failed


def download():
    """Fetch the Kaggle dataset (public, no API key needed) if it isn't on disk yet."""
    if any(RAW.glob("*.csv")):
        return
    RAW.mkdir(parents=True, exist_ok=True)
    print(f"Downloading Kaggle dataset → {RAW}")
    zip_path, _ = urllib.request.urlretrieve(KAGGLE_URL)
    zipfile.ZipFile(zip_path).extractall(RAW)


def main():
    download()
    DB.parent.mkdir(parents=True, exist_ok=True)
    MARTS.mkdir(parents=True, exist_ok=True)
    con = duckdb.connect(str(DB))

    print("Building warehouse")
    for f in ["10_staging.sql", "20_marts.sql", "30_analytics.sql"]:
        run_sql(con, SQL / f)

    fc, aic = revenue_forecast(con)
    print(f"  ✓ revenue_forecast       ETS (A,Ad,N) on Jan 2017-Aug 2018, Sep-Dec 2018 = R${fc.forecast_revenue.sum() / 1e6:,.2f}M (AIC {aic:,.0f})")
    clv = predicted_clv(con)
    print(f"  ✓ predicted_clv_12m      BG/NBD r={clv['r']:.3f} α={clv['alpha']:.1f} a={clv['a']:.2f} b={clv['b']:.2f} · "
          f"Gamma-Gamma p={clv['p']:.2f} q={clv['q']:.2f} v={clv['v']:.1f} · {clv['repeat_customers']:,} repeat buyers · "
          f"next 12M R${clv['total'] / 1e3:,.0f}K")

    blanks = write_plan(con)
    plan_mirror(con)
    nulls = con.execute("select count(*) from mart.category_plan where plan_revenue is null").fetchone()[0]
    print(f"  ✓ data/plan/category_plan_{{2017,2018}}.csv  (SYNTHETIC; {blanks} 'n/a'/'-' cells -> {nulls} nulls after cleaning)")

    print("Data-quality tests")
    failed = run_tests(con)
    for name, query in plan_tests(con):
        if query is None:  # the TOTAL row of each file vs the cleaned lines
            bad = 0
            for year in (2017, 2018):
                with open(PLAN / f"category_plan_{year}.csv", encoding="utf-8") as fh:
                    total = sum(float(v) for v in next(r for r in csv.reader(fh) if r[0] == "TOTAL")[2:14])
                lines = con.execute(f"select sum(plan_revenue) from mart.category_plan where year = {year}").fetchone()[0]
                bad += abs(total - lines) > 1
        else:
            bad = con.execute(query).fetchone()[0]
        failed += bad > 0
        print(f"  {'✓' if bad == 0 else '✗'} {name}{'' if bad == 0 else f'  ({bad} rows)'}")
    if failed:
        sys.exit(f"{failed} test(s) failed — marts not exported")

    print("Exporting marts for Power BI")
    for table in EXPORTS:
        out = MARTS / f"{table}.csv"
        con.execute(f"copy mart.{table} to '{out.as_posix()}' (header, delimiter ',')")
        con.execute(f"copy mart.{table} to '{out.with_suffix('.parquet').as_posix()}' (format parquet)")
        n = con.execute(f"select count(*) from mart.{table}").fetchone()[0]
        print(f"  → {table:<22} {n:>9,} rows  (.csv + .parquet)")


if __name__ == "__main__":
    main()
